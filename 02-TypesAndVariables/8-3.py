temperature_in_celsius = int(input("Enter temperature in celsius: "))
temperature_in_fahrenheit = (temperature_in_celsius * 9/5) + 32
temperature_in_kelvin = temperature_in_celsius + 273.15

print(f'Temperature in celsius: {temperature_in_celsius}\nTemperature in fahrenheit: {temperature_in_fahrenheit}\nTemperature in kelvin: {temperature_in_kelvin}')